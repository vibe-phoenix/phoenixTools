#  Retro pixel panel (PySide2 / PySide6), frameless, Silkscreen font embedded.
#   SCENE        current scene name (scrolls if too long)
#   SAVE EVERY   HR : MIN : SEC · COPIES · STATUS (click to start / stop)
#                type values, then APPLY (or Enter)
#   OPTIONS      RESCUE · POP-UPS · MSG EVERY SAVE
#   NEXT SAVE IN progress blocks + countdown
#   Buttons      APPLY · DEFAULTS · SAVE NOW · FOLDER
