def _arm_autosave(*_):
    """Start autosave using effective (global-or-project) settings, exactly
    once. This is the function that was previously misnamed/missing."""
    global _STARTED
    if _STARTED:
        return
    _maybe_rescue_from_autosave()
    _apply_effective_settings()
    _start_untitled_timer(5.0)
    _STARTED = True

def _on_new_or_open(*_):
    _reset_untitled_reminder()
    _maybe_rescue_from_autosave()
    if not _MANUAL_OVERRIDE:
        _apply_effective_settings()
    else:
        if _STARTED and _AUTOSAVE_TIMER_ID is None:
            start_autosave(_AUTOSAVE_SETTINGS["interval_sec"], _AUTOSAVE_SETTINGS["keep"], manual=True)
        if _HOURLY_RUNTIME_ON and _HOURLY_TIMER_ID is None:
            _start_hourly_timer()

def _install_jobs():
    global _SCENE_RESET_JOBS
    for jid in _SCENE_RESET_JOBS:
        try: cmds.scriptJob(kill=jid, force=True)
        except Exception: pass
    _SCENE_RESET_JOBS = []
    for ev in ("NewSceneOpened", "SceneOpened"):
        try:
            _SCENE_RESET_JOBS.append(cmds.scriptJob(event=[ev, _on_new_or_open], protected=True))
        except Exception:
            pass
    # SceneSaved is intentionally NOT in this list — autosave calls file(save=True)
    # which fires SceneSaved, which would re-arm and multiply the timer callbacks

def _arm_idle_start():
    try:
        cmds.scriptJob(runOnce=True, event=("idle", _after_ui_ready))
    except Exception:
        try: mu.executeDeferred(_after_ui_ready)
        except Exception: pass

def _after_ui_ready():
    try:
        if not cmds.window("MayaWindow", exists=True):
            _arm_idle_start()
            return
        _install_jobs()
        _arm_autosave()
    except Exception:
        try: _arm_idle_start()
        except Exception: pass

def bootstrap():
    """Entry point. Call from userSetup.py."""
    if cmds.about(batch=True):
        return
    _arm_idle_start()

