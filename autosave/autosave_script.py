def _icon_pixels(theme):
    """16x16 grid of hex colours (None = transparent)."""
    col = {"#": theme["ink"], "b": theme["bg"], "s": theme["mid"], "l": theme["nt"],
           "n": theme["nt"], "a": theme["acc"]}
    g = [[None] * 16 for _ in range(16)]
    for layer, ox, oy in ((_ICON_MAP, 0, 0), (_ICON_CLOCK, 9, 9)):
        for y, row in enumerate(layer):
            for x, ch in enumerate(row):
                if ch != " " and 0 <= y + oy < 16 and 0 <= x + ox < 16:
                    g[y + oy][x + ox] = col[ch]
    return g

def _icon_image(theme, scale=2):
    img = QtGui.QImage(16 * scale, 16 * scale, QtGui.QImage.Format_ARGB32)
