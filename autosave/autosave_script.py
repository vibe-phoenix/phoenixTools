def _load_project_settings():
    try:
        if cmds.optionVar(exists=_OPT_PROJECTS):
            raw = cmds.optionVar(q=_OPT_PROJECTS)
            data = json.loads(raw) if raw else {}
            if isinstance(data, dict):
                return data
    except Exception:
        pass
    return {}

def _save_project_settings(data):
    try:
        cmds.optionVar(sv=(_OPT_PROJECTS, json.dumps(data)))
    except Exception:
        pass

def _project_key(dir_path):
    norm = os.path.normpath(dir_path)
    return norm.lower() if os.name == "nt" else norm

def _get_project_override(dir_path):
    if not dir_path:
        return None
    return _load_project_settings().get(_project_key(dir_path))

def _set_project_override(dir_path, interval_sec, keep, hourly_enabled):
    data = _load_project_settings()
    data[_project_key(dir_path)] = {
        "interval_sec":   max(10, int(interval_sec)),
        "keep":           max(1, int(keep)),
        "hourly_enabled": bool(hourly_enabled),
        "display_path":   os.path.normpath(dir_path),
    }
    _save_project_settings(data)

def _clear_project_override(dir_path_or_key):
    data = _load_project_settings()
    key = _project_key(dir_path_or_key) if os.sep in dir_path_or_key or "/" in dir_path_or_key else dir_path_or_key
    data.pop(key, None)
    _save_project_settings(data)


