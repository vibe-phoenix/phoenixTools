def _flush_scene():
    scene_path = _current_scene_path()
    if not scene_path:
        return False
    try:
        cmds.file(save=True)
    except Exception as e:
        print(f"[AutoSave] Warning: could not flush scene: {e}")
    return True

def _format_size(num_bytes):
    try:
        n = float(num_bytes)
    except Exception:
        return "—"
    if n < 1024.0:
        return f"{int(n)}B"
    for unit in ("KB", "MB", "GB"):
        n /= 1024.0
        if n < 1024.0 or unit == "GB":
            return f"{n:.1f}{unit}"
    return f"{n:.1f}GB"

def _copy_scene(scene_path, dest_dir, label):
    """Copy scene_path into dest_dir with a timestamped name, verify it,
    retry once on failure, quarantine as .CORRUPT if still bad.
    Returns dest_path on success, None on failure/quarantine."""
    scene_path = os.path.normpath(scene_path)
    dest_dir   = os.path.normpath(dest_dir)
    _, ext     = os.path.splitext(os.path.basename(scene_path))
    try:
        expected_size = os.path.getsize(scene_path)
    except Exception:
        expected_size = None

    for attempt in range(2):
        timestamp = time.strftime("%d-%m-%Y_%H-%M-%S")
        dest_name = f"{label}_{timestamp}{ext}"
        dest_path = os.path.normpath(os.path.join(dest_dir, dest_name))
        dest_open = ("\\\\" + "?\\" + dest_path) if os.name == "nt" else dest_path
        try:
            with open(dest_open, "wb") as fdst:
                with open(scene_path, "rb") as fsrc:
                    shutil.copyfileobj(fsrc, fdst)
            shutil.copystat(scene_path, dest_path)
        except Exception as e:
            _notify(f"{label} backup failed: {e}", "error", force=True)
            return None

        ok, reason = _verify_backup_integrity(dest_path, expected_size)
        if ok:
            return dest_path

        if attempt == 0:
            try: os.remove(dest_path)
            except Exception: pass
            time.sleep(0.3)
            continue

        corrupt_path = dest_path + ".CORRUPT"
        try:
            if os.path.exists(corrupt_path):
                os.remove(corrupt_path)
            os.rename(dest_path, corrupt_path)
        except Exception:
            pass
        _notify(f"{label} backup failed verification ({reason}) — quarantined", "warning", force=True)
        _purge_corrupt(dest_dir)
        return None
    return None


