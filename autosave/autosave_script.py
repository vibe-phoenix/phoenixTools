def _maybe_rescue_from_autosave():
    """If the currently-open scene is an autosave/hourly file, Save-As it back
    to the original scene location — unless this open was an intentional
    'preview a backup' action from the Version Browser."""
    global _SUPPRESS_RESCUE_ONCE
    if _SUPPRESS_RESCUE_ONCE:
        _SUPPRESS_RESCUE_ONCE = False
        return
    if not _rescue_enabled():
        return
    scene_path = _current_scene_path()
    if not scene_path or not _RESCUE_FILE_RE.match(os.path.basename(scene_path)):
        return
    scene_name  = _original_scene_name(scene_path)
    target_dir  = _original_scene_dir(scene_path)
    target_path = os.path.join(target_dir, scene_name)
    ext         = os.path.splitext(scene_name)[1].lower().lstrip(".")
    try:
        cmds.file(rename=target_path)
        cmds.file(save=True, type="mayaAscii" if ext == "ma" else "mayaBinary", force=True)
        _notify(f"Rescued into original location: {target_path}", force=True)
    except Exception as e:
        _notify(f"Rescue failed: {e}", "error", force=True)


