def _list_backups_for_scene(scene_path):
    """Returns list of dicts sorted newest-first: path, label, timestamp_str,
    epoch, size, corrupt."""
    results = []
    if not scene_path:
        return results
    true_path = _true_scene_path_for_listing(scene_path)
    sources = [("autosave", _autosave_dir_for_scene, _AUTOSAVE_FILE_RE)]
    if _HOURLY_FEATURE_ON:
        sources.append(("hourly", _hourly_dir_for_scene, _HOURLY_FILE_RE))
    for label, dir_fn, pattern in sources:
        try:
            d = dir_fn(true_path)
        except Exception:
            continue
        try:
            for f in os.listdir(d):
                full = os.path.join(d, f)
                corrupt = f.endswith(".CORRUPT")
                if not (pattern.match(f) or corrupt):
                    continue
                try:
                    mtime = os.path.getmtime(full)
                    size  = os.path.getsize(full)
                except Exception:
                    continue
                results.append({
                    "path": full, "label": label,
                    "timestamp_str": time.strftime("%d-%m-%Y %H:%M:%S", time.localtime(mtime)),
                    "epoch": mtime, "size": size, "corrupt": corrupt,
                })
        except Exception:
            pass
    results.sort(key=lambda r: r["epoch"], reverse=True)
    return results

def _corrupt_count_for_scene(scene_path):
    if not scene_path:
        return 0
    true_path = _true_scene_path_for_listing(scene_path)
    count = 0
    for dir_fn in ((_autosave_dir_for_scene, _hourly_dir_for_scene) if _HOURLY_FEATURE_ON else (_autosave_dir_for_scene,)):
        try:
            d = dir_fn(true_path)
            count += len([f for f in os.listdir(d) if f.endswith(".CORRUPT")])
        except Exception:
            pass
    return count

