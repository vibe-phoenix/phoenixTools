# INTEGRITY VERIFICATION
# =========================================================================

_MA_HEADER_TOKENS = (b"//Maya ASCII", b"requires maya", b"//Maya")
_MB_MAGIC         = (b"FOR4", b"FOR8")

def _verify_backup_integrity(dest_path, expected_size=None):
    """Sanity-checks a freshly written backup. Returns (ok, reason)."""
    ext = os.path.splitext(dest_path)[1].lower().lstrip(".")
    try:
        actual_size = os.path.getsize(dest_path)
    except Exception as e:
        return False, f"cannot stat file ({e})"
    if actual_size == 0:
        return False, "zero-byte file"
    if expected_size is not None and actual_size != expected_size:
        return False, f"size mismatch (expected {expected_size}, got {actual_size})"
    try:
        with open(dest_path, "rb") as f:
            head = f.read(256)
        if ext == "mb":
            if not head.startswith(_MB_MAGIC):
                return False, "missing binary scene header (truncated/corrupt .mb)"
        elif ext == "ma":
            if not any(tok in head for tok in _MA_HEADER_TOKENS):
                return False, "missing ASCII scene header (truncated/corrupt .ma)"
    except Exception as e:
        return False, f"read error ({e})"
    return True, "ok"

def _purge_corrupt(folder):
    try:
        files = [f for f in os.listdir(folder) if f.endswith(".CORRUPT")]
        paths = sorted([os.path.join(folder, f) for f in files], key=os.path.getmtime, reverse=True)
        for p in paths[_CORRUPT_KEEP:]:
            try: os.remove(p)
            except Exception: pass
    except Exception:
        pass


# =========================================================================
# PURGE  (rolling autosaves only — hourly files are never deleted)
# =========================================================================

_AUTOSAVE_FILE_RE = re.compile(
    r"^autosave_\d{2}-\d{2}-\d{4}_\d{2}-\d{2}-\d{2}\.(ma|mb)$", re.IGNORECASE
)
_HOURLY_FILE_RE = re.compile(
    r"^hourly_\d{2}-\d{2}-\d{4}_\d{2}-\d{2}-\d{2}\.(ma|mb)$", re.IGNORECASE
)

def _purge_old(autosave_dir, keep):
    try:
        all_files = os.listdir(autosave_dir)
        files     = [f for f in all_files if _AUTOSAVE_FILE_RE.match(f)]
        paths = sorted(
            [os.path.join(autosave_dir, f) for f in files],
            key=os.path.getmtime, reverse=True
        )
        to_delete = paths[keep:]
        for old_path in to_delete:
            try:
                os.remove(old_path)
            except Exception as e:
                print(f"[AutoSave] Purge: failed to delete {os.path.basename(old_path)}: {e}")
    except Exception as e:
        print(f"[AutoSave] Purge error: {e}")


