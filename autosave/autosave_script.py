def _current_scene_path():
    return cmds.file(q=True, sn=True)

def _scene_base(scene_path):
    return os.path.splitext(os.path.basename(scene_path))[0]

def _make_dir(path):
    if not os.path.exists(path):
        try:
            os.makedirs(path)
        except Exception as e:
            print(f"[AutoSave] ERROR creating dir {repr(path)}: {e}")
    return path

def _autosave_dir_for_scene(scene_path):
    scene_path = os.path.normpath(scene_path)
    root  = os.path.normpath(os.path.join(os.path.dirname(scene_path), "autosaves"))
    final = os.path.normpath(os.path.join(root, _scene_base(scene_path) + "_autosave"))
    _make_dir(root); _make_dir(final)
    return final

def _hourly_dir_for_scene(scene_path):
    scene_path = os.path.normpath(scene_path)
    root  = os.path.normpath(os.path.join(os.path.dirname(scene_path), "autosaves"))
    final = os.path.normpath(os.path.join(root, _scene_base(scene_path) + "_hourly"))
    _make_dir(root); _make_dir(final)
    return final

def _original_scene_dir(scene_path):
    """Return the directory above 'autosaves' in the given path."""
    norm  = os.path.normpath(scene_path)
    parts = norm.split(os.sep)
    lower = [p.lower() for p in parts]
    if "autosaves" in lower:
        i = lower.index("autosaves")
        if i > 0:
            return os.sep.join(parts[:i])
    return os.path.dirname(os.path.dirname(os.path.dirname(norm)))

def _original_scene_name(scene_path):
    """Derive the original scene filename from the autosave/hourly folder name."""
    norm   = os.path.normpath(scene_path)
    folder = os.path.basename(os.path.dirname(norm))
    _, ext = os.path.splitext(norm)
    if folder.endswith("_autosave"):
        base = folder[:-len("_autosave")]
    elif folder.endswith("_hourly"):
        base = folder[:-len("_hourly")]
    else:
        base = folder
    return base + ext

_RESCUE_FILE_RE = re.compile(
    r"^(?:autosave|hourly)_\d{2}-\d{2}-\d{4}_\d{2}-\d{2}-\d{2}\.(?:ma|mb)$", re.IGNORECASE
)

def _true_scene_path_for_listing(scene_path):
    """If the currently open scene IS itself a backup file (e.g. user opened
    one to inspect it), resolve back to what the real original scene path
    would be, so settings lookup / version listing stay correct."""
    if scene_path and _RESCUE_FILE_RE.match(os.path.basename(scene_path)):
        target_dir  = _original_scene_dir(scene_path)
        target_name = _original_scene_name(scene_path)
        return os.path.join(target_dir, target_name)
    return scene_path


