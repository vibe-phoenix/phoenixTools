    def _edit_color(self, key):
        t = _T()
        old = t[key]
        dlg = QtWidgets.QColorDialog(QtGui.QColor(old), self)
        dlg.setWindowTitle(dict(_THEME_KEYS)[key].title() + " colour")

        def live(c):
            if c.isValid():
                t[key] = c.name()
                self._repaint_all()
        dlg.currentColorChanged.connect(live)
        if _exec(dlg):
            t[key] = dlg.currentColor().name()
        else:
            t[key] = old
        _save_theme_state()
        self._repaint_all()

    # ── refresh ──────────────────────────────────────────────────────────
    def _fields(self):
        return (self.f_hr, self.f_min, self.f_sec, self.f_keep)

    def _next_save(self):
        if _AUTOSAVE_TIMER_ID is None:
            return None, 0.0
        interval = float(max(1, _AUTOSAVE_SETTINGS["interval_sec"]))
        cands = [t for t in (_AUTOSAVE_ARMED_AT, _AUTOSAVE_LAST.get("epoch")) if t]
        if not cands:
            return None, 0.0
        elapsed = (time.time() - max(cands)) % interval
        return interval - elapsed, elapsed / interval

    def _tick(self):
        running = _AUTOSAVE_TIMER_ID is not None
        remaining, prog = self._next_save()
        self.blocks.setLit(int(round(prog * _Blocks.N)) if running else 0)
        self.cd.setText(_hms(remaining) if (running and remaining is not None) else "--:--:--")

    def _refresh(self):
        try:
            st = autosave_status()
        except Exception as e:
            print(f"[AutoSave] UI refresh error: {e}")
            return
        self.status.setOn(st["running"])
        if not self._pending and not any(f.hasFocus() for f in self._fields()):
            hh, rem = divmod(int(st["interval_sec"]), 3600)
            mm, ss = divmod(rem, 60)
            self.f_hr.setValue(min(hh, 99)); self.f_min.setValue(mm); self.f_sec.setValue(ss)
            self.f_keep.setValue(st["keep"])
        self.c_resc.setChecked(st["rescue_on_open"])
        self.c_note.setChecked(st["notify_master"])
        self.c_tick.setChecked(st["notify_every_tick"])
        scene = st["scene_path"]
        self.scene.setText(os.path.basename(_true_scene_path_for_listing(scene)) if scene
                           else "UNTITLED - SAVE THE SCENE FIRST")

    # ── pending edits ────────────────────────────────────────────────────
    def _mark_pending(self, *_):
        self._pending = True
        self.b_apply.setHot(True)

    def _clear_pending(self):
        self._pending = False
        self.b_apply.setHot(False)

    def _values(self):
        for f in self._fields():
            f._normalize()
        total = self.f_hr.value() * 3600 + self.f_min.value() * 60 + self.f_sec.value()
        return max(10, total), max(1, self.f_keep.value())

    # ── actions ──────────────────────────────────────────────────────────
    def _apply(self):
        total, keep = self._values()
        start_autosave(total, keep, manual=True)
        self._clear_pending()
        self._refresh(); self._tick()

    def _defaults(self):
        global _MANUAL_OVERRIDE
        _MANUAL_OVERRIDE = False
        _apply_effective_settings()
        self._clear_pending()
        self._refresh(); self._tick()

    def _arm(self):
        if _AUTOSAVE_TIMER_ID is not None:
            stop_autosave()
        else:
            start_autosave(_AUTOSAVE_SETTINGS["interval_sec"], _AUTOSAVE_SETTINGS["keep"], manual=True)
        self._refresh(); self._tick()

    def _save_now(self):
        if not _current_scene_path():
            _confirm(title="Autosave", message="Scene is untitled.\nSave the scene first.", button=["OK"])
            return
        force_save_now()
        self._refresh(); self._tick()

    def closeEvent(self, e):
        global _UI_INSTANCE
        if self._pending:
            res = _confirm(title="Unapplied changes",
                           message="You changed the timing but did not apply it. Apply before closing?",
                           button=["Cancel", "Discard", "Apply"],
                           defaultButton="Apply", cancelButton="Cancel", dismissString="Cancel")
            if res == "Cancel":
                e.ignore()
                return
            if res == "Apply":
                self._apply()
            else:
                self._clear_pending()
        _save_theme_state()
        for t in (self._timer, self._ttimer):
            try: t.stop()
            except Exception: pass
        _UI_INSTANCE = None
        super(_AutosaveWindow, self).closeEvent(e)


