def _reset_untitled_reminder(*_):
    _UNTITLED_REMINDERS["enabled"]    = True
    _UNTITLED_REMINDERS["last_epoch"] = 0.0

def _maybe_prompt_untitled():
    now = time.time()
    if not _UNTITLED_REMINDERS["enabled"]:
        return
    if now - _UNTITLED_REMINDERS["last_epoch"] < _UNTITLED_REMINDERS["interval_sec"]:
        return
    _UNTITLED_REMINDERS["last_epoch"] = now
    try:
        result = _confirm(
            title="Untitled Scene",
            message="Untitled project detected.\nSave now to enable autosaves?",
            button=["Save Now", "Don't remind me again", "Later"],
            defaultButton="Save Now", cancelButton="Later", dismissString="Later"
        )
        if result == "Save Now":
            try:   mel.eval('SaveSceneAs;')
            except Exception:
                try: cmds.file(save=True, prompt=True)
                except Exception: pass
        elif result == "Don't remind me again":
            _UNTITLED_REMINDERS["enabled"] = False
    except Exception:
        pass

def _untitled_timer_cb(elapsed, last, data):
    try:
        if not _current_scene_path():
            _maybe_prompt_untitled()
    except Exception:
        pass

def _start_untitled_timer(period_sec=5.0):
    global _UNTITLED_TIMER_ID
    if _UNTITLED_TIMER_ID is not None:
        return
    try:
        _UNTITLED_TIMER_ID = om.MTimerMessage.addTimerCallback(float(period_sec), _untitled_timer_cb)
    except Exception:
        _UNTITLED_TIMER_ID = None

def _stop_untitled_timer():
    global _UNTITLED_TIMER_ID
    if _UNTITLED_TIMER_ID is not None:
        try: om.MTimerMessage.removeCallback(_UNTITLED_TIMER_ID)
        except Exception: pass
        _UNTITLED_TIMER_ID = None


# =========================================================================
# ROLLING AUTOSAVE
# =========================================================================

def _autosave_timer_cb(elapsed, last, data):
    try:
        scene_path = _current_scene_path()
        if not scene_path:
            return
        _flush_scene()
        autosave_dir = _autosave_dir_for_scene(scene_path)
        dest = _copy_scene(scene_path, autosave_dir, "autosave")
        if dest:
            _AUTOSAVE_LAST.update({
                "path": dest, "timestamp_str": time.strftime("%d-%m-%Y_%H-%M-%S"), "epoch": time.time()
            })
            _purge_old(autosave_dir, _AUTOSAVE_SETTINGS["keep"])
            if _notify_every_tick_enabled():
                _notify(f"Autosaved at {time.strftime('%H:%M:%S')}")
    except Exception as e:
        print(f"[AutoSave] Autosave tick error: {e}")

def stop_autosave():
    global _AUTOSAVE_TIMER_ID
    if _AUTOSAVE_TIMER_ID is not None:
        try: om.MTimerMessage.removeCallback(_AUTOSAVE_TIMER_ID)
        except Exception: pass
        _AUTOSAVE_TIMER_ID = None

def start_autosave(interval_sec=30, keep=_DEFAULT_KEEP, manual=True):
    """manual=True marks this as a deliberate user/session override (sticky
    across scene changes). Internal/automatic application uses manual=False."""
    global _AUTOSAVE_TIMER_ID, _AUTOSAVE_SETTINGS, _STARTED, _MANUAL_OVERRIDE, _AUTOSAVE_ARMED_AT
    stop_autosave()
    _AUTOSAVE_ARMED_AT = time.time()
    interval_sec = max(10, int(interval_sec))
    keep         = max(1,  int(keep))
    _AUTOSAVE_SETTINGS = {"interval_sec": interval_sec, "keep": keep}
    try:
        _AUTOSAVE_TIMER_ID = om.MTimerMessage.addTimerCallback(float(interval_sec), _autosave_timer_cb)
    except Exception:
        _AUTOSAVE_TIMER_ID = None
    _STARTED = True
    if manual:
        _MANUAL_OVERRIDE = True


