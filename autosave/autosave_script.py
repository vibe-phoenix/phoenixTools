# =========================== autosave_script.py ===========================
# QUICK INSTALL — drag install_autosave.py (kept next to this file) into
#   the Maya viewport. It copies this script, sets up userSetup.py, adds the
#   shelf button and starts autosave right away.
#
# MANUAL SETUP — Run once to install, then loads automatically every Maya launch:
#
#   1. Save this file to your Maya scripts folder:
#        Windows:  C:/Users/<you>/Documents/maya/scripts/autosave_script.py
#        Mac:      ~/Library/Preferences/Autodesk/maya/scripts/autosave_script.py
#        Linux:    ~/maya/scripts/autosave_script.py
#
#   2. Add to userSetup.py (same scripts folder, create if missing):
#        import autosave_script
#        autosave_script.bootstrap()
#
#   3. Restart Maya. Script arms automatically on startup.
#      Open the UI anytime:  autosave_script.autosave_status_ui()
#
