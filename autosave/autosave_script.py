def _notify(message, kind="info", force=False, fade_time=2500):
    """Shows an in-viewport toast (unless suppressed by the master toggle) and
    always prints to the script editor. kind: info | warning | error.
    force=True bypasses the master toggle — used for things the user should
    not be able to silently miss (errors, corrupt quarantines, rescues)."""
    print(f"[AutoSave] {message}")
    if not force and not _notify_master_enabled():
        return
    tag = {"info": "Autosave", "warning": "Autosave Warning", "error": "Autosave Error"}.get(kind, "Autosave")
    try:
        _show_toast(message, kind, fade_time + 1500)   # custom panel (defined in UI section)
    except Exception:
        try:
            cmds.inViewMessage(amg=f"<hl>{tag}:</hl> {message}", pos="midCenterTop",
                                fade=True, fadeStaleTime=fade_time, dragKill=True, fontSize=10)
        except Exception:
            pass


