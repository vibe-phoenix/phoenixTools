def _load_startup_defaults():
    try:
        mins = int(cmds.optionVar(q=_OPT_MIN))  if cmds.optionVar(exists=_OPT_MIN)  else _DEFAULT_MIN
        secs = int(cmds.optionVar(q=_OPT_SEC))  if cmds.optionVar(exists=_OPT_SEC)  else _DEFAULT_SEC
        keep = int(cmds.optionVar(q=_OPT_KEEP)) if cmds.optionVar(exists=_OPT_KEEP) else _DEFAULT_KEEP
        mins = max(0, mins);  secs = max(0, min(59, secs));  keep = max(1, keep)
        total = max(10, mins * 60 + secs)
        return {"minutes": mins, "seconds": secs, "interval_sec": total, "keep": keep}
    except Exception:
        total = max(10, _DEFAULT_MIN * 60 + _DEFAULT_SEC)
        return {"minutes": _DEFAULT_MIN, "seconds": _DEFAULT_SEC,
                "interval_sec": total, "keep": _DEFAULT_KEEP}

