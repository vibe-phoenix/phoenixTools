def _effective_settings_for_scene(scene_path):
    sd = _load_startup_defaults()
    base = {
        "interval_sec":   sd["interval_sec"],
        "keep":           sd["keep"],
        "hourly_enabled": _hourly_enabled_global_default(),
        "source":         "global",
    }
    if not scene_path:
        return base
    true_path = _true_scene_path_for_listing(scene_path)
    override = _get_project_override(os.path.dirname(true_path))
    if override:
        return {
            "interval_sec":   max(10, int(override.get("interval_sec", base["interval_sec"]))),
            "keep":           max(1,  int(override.get("keep", base["keep"]))),
            "hourly_enabled": bool(override.get("hourly_enabled", base["hourly_enabled"])),
            "source":         "project",
        }
    return base

